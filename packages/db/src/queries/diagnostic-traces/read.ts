// Diagnostic trace reads: owner-scoped list/detail plus the admin variants.

import { and, desc, eq } from 'drizzle-orm';

import { getDb, schema } from '../../client';
import type { DiagnosticTraceRow } from './types';

export async function listDiagnosticTraces(
  userId: string | undefined,
  opts: { threadId?: string | undefined; limit?: number } = {},
): Promise<DiagnosticTraceRow[]> {
  const conditions: ReturnType<typeof and>[] = [];
  if (userId) conditions.push(eq(schema.diagnosticTraces.userId, userId));
  if (opts.threadId) conditions.push(eq(schema.diagnosticTraces.threadId, opts.threadId));

  const db = getDb();
  return db
    .select()
    .from(schema.diagnosticTraces)
    .where(conditions.length > 0 ? and(...conditions) : undefined)
    .orderBy(desc(schema.diagnosticTraces.startedAt))
    .limit(Math.min(100, Math.max(1, opts.limit ?? 20)));
}

export async function getDiagnosticTrace(
  userId: string | undefined,
  id: string,
): Promise<DiagnosticTraceRow | null> {
  const db = getDb();
  const rows = await db
    .select()
    .from(schema.diagnosticTraces)
    .where(
      userId
        ? and(eq(schema.diagnosticTraces.id, id), eq(schema.diagnosticTraces.userId, userId))
        : eq(schema.diagnosticTraces.id, id),
    )
    .limit(1);
  return rows[0] ?? null;
}

/**
 * Privileged admin read. Callers must have already passed the admin
 * authorization boundary; this intentionally does not scope to an admin's
 * own userId because admins investigate traces generated by other users.
 */
export async function getDiagnosticTraceForAdmin(id: string): Promise<DiagnosticTraceRow | null> {
  return getDiagnosticTrace(undefined, id);
}

/**
 * Privileged admin list. Callers must have already passed the admin
 * authorization boundary; this intentionally returns traces across users.
 */
export async function listDiagnosticTracesForAdmin(
  opts: { threadId?: string | undefined; limit?: number } = {},
): Promise<DiagnosticTraceRow[]> {
  return listDiagnosticTraces(undefined, opts);
}
