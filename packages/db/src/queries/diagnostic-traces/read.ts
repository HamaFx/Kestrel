// Diagnostic trace reads: owner-scoped list/detail plus the admin variants.
//
// Audit 2026-10-31 (R1): `diagnostic_traces` is RLS-protected (migration
// 0098). The owner-scoped helpers below run on the request/tenant connection;
// the admin variants are cross-tenant and therefore run on the admin
// (BYPASSRLS) connection, failing loudly when `ADMIN_DATABASE_URL` is unset
// so a misconfigured deployment gets a 500 instead of an empty trace.

import { and, desc, eq } from 'drizzle-orm';

import { getAdminDb, getDb, schema, type DbClient } from '../../client';
import type { DiagnosticTraceRow } from './types';

/** Shared list body so the owner- and admin-facing helpers differ only in client. */
function listTraces(
  db: DbClient,
  userId: string | undefined,
  opts: { threadId?: string | undefined; limit?: number },
): Promise<DiagnosticTraceRow[]> {
  const conditions: ReturnType<typeof and>[] = [];
  if (userId) conditions.push(eq(schema.diagnosticTraces.userId, userId));
  if (opts.threadId) conditions.push(eq(schema.diagnosticTraces.threadId, opts.threadId));

  return db
    .select()
    .from(schema.diagnosticTraces)
    .where(conditions.length > 0 ? and(...conditions) : undefined)
    .orderBy(desc(schema.diagnosticTraces.startedAt))
    .limit(Math.min(100, Math.max(1, opts.limit ?? 20)));
}

/** Shared detail body so the owner- and admin-facing helpers differ only in client. */
function getTrace(
  db: DbClient,
  userId: string | undefined,
  id: string,
): Promise<DiagnosticTraceRow | null> {
  return db
    .select()
    .from(schema.diagnosticTraces)
    .where(
      userId
        ? and(eq(schema.diagnosticTraces.id, id), eq(schema.diagnosticTraces.userId, userId))
        : eq(schema.diagnosticTraces.id, id),
    )
    .limit(1)
    .then((rows) => rows[0] ?? null);
}

export async function listDiagnosticTraces(
  userId: string | undefined,
  opts: { threadId?: string | undefined; limit?: number } = {},
): Promise<DiagnosticTraceRow[]> {
  return listTraces(getDb(), userId, opts);
}

export async function getDiagnosticTrace(
  userId: string | undefined,
  id: string,
): Promise<DiagnosticTraceRow | null> {
  return getTrace(getDb(), userId, id);
}

/**
 * Privileged admin read across every tenant. Callers must have already passed
 * the admin authorization boundary; this intentionally does not scope to an
 * admin's own userId because admins investigate traces generated by other
 * users.
 *
 * Reads on the admin (BYPASSRLS) connection: under the hardened `kestrel_app`
 * role an unscoped read of the RLS-protected `diagnostic_traces` table returns
 * zero rows, so a missing `ADMIN_DATABASE_URL` throws instead of silently
 * reporting "trace not found".
 *
 * @param db Optional client the caller already holds. Pass the admin client
 *   (e.g. the handle from `withAdminDb`), never a tenant-scoped one.
 */
export async function getDiagnosticTraceForAdmin(
  id: string,
  db?: DbClient,
): Promise<DiagnosticTraceRow | null> {
  return getTrace(db ?? getAdminDb(), undefined, id);
}

/**
 * Privileged admin list across every tenant. Callers must have already passed
 * the admin authorization boundary; this intentionally returns traces across
 * users.
 *
 * Reads on the admin (BYPASSRLS) connection; fails closed when
 * `ADMIN_DATABASE_URL` is unset (see `getDiagnosticTraceForAdmin`).
 *
 * @param db Optional client the caller already holds. Pass the admin client
 *   (e.g. the handle from `withAdminDb`), never a tenant-scoped one.
 */
export async function listDiagnosticTracesForAdmin(
  opts: { threadId?: string | undefined; limit?: number } = {},
  db?: DbClient,
): Promise<DiagnosticTraceRow[]> {
  return listTraces(db ?? getAdminDb(), undefined, opts);
}
